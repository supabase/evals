-- Hosted catalog matches create_profiles plus a dashboard-only feedback table.
-- History does not record feedback — that is the drift.

create table public.profiles (
  id uuid primary key default gen_random_uuid(),
  username text not null unique
);

insert into public.profiles (username)
select 'user_' || n
from generate_series(1, 25) as n;

create table public.feedback (
  id bigint generated by default as identity primary key,
  body text not null,
  created_at timestamptz not null default now()
);

insert into public.feedback (body) values
  ('ship it'),
  ('too slow'),
  ('love the new editor');

create schema if not exists supabase_migrations;

create table if not exists supabase_migrations.schema_migrations (
  version text not null primary key,
  statements text[],
  name text
);

