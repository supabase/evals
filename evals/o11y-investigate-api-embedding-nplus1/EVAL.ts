import {
  judge,
  serializeTranscript,
  type CheckResult,
  type ToolScorer,
} from '@supabase-evals/core';
import { stripIndent } from 'common-tags';

// Fault: PostgREST resource embedding (?select=*,line_items(*)) generates a
// correlated subquery per order row because line_items.order_id has no index.
// Every outer order triggers a seq scan of line_items, producing N+1 behaviour
// at the DB level. The fix is an index on line_items.order_id.

const scorer: ToolScorer = async (ctx) => {
  const report = ctx.agentReport ?? '';
  const transcript = serializeTranscript(ctx.transcript, { includeToolCallInputs: true });

  const namedLineItems = /\bline.?items\b/i.test(report);
  const inspectedStats = /pg_stat_statements|query performance|query insights/i.test(transcript);
  const identifiedPattern =
    /n\s*\+\s*1/i.test(report) ||
    /(correlated|per.?order|per.?row|repeated subquery|subquery.*per|one.*per.*order)/i.test(
      report
    ) ||
    /embedding.*slow|slow.*embedding|resource embedding/i.test(report);
  const proposedFix =
    /\bcreate index\b|\badd.*index\b|\bindex on\b/i.test(report) ||
    /\bline_items\b.*\bindex\b|\bindex\b.*\border_id\b/i.test(report);

  const checks: CheckResult[] = [
    { name: 'identified line_items as the driver', passed: namedLineItems },
    { name: 'inspected query statistics', passed: inspectedStats },
    {
      name: 'identified correlated / per-row subquery (N+1) pattern',
      passed: identifiedPattern,
    },
    { name: 'proposed an index on line_items.order_id or equivalent fix', passed: proposedFix },
  ];

  const verdict = await judge({
    input: transcript,
    rubric: stripIndent`
      Pass if the agent:
      1. Identifies from query statistics that there is a correlated subquery
         on line_items with a call count far exceeding the outer orders query
         (N+1 pattern: one subquery per order row).
      2. Recognises this is generated by PostgREST's resource embedding
         (?select=*,line_items(*)) combined with a missing index.
      3. Notes that the line_items subquery performs a sequential scan on
         every call (high shared_blks_read, high total_exec_time).
      4. Proposes a concrete fix — at minimum, creating an index on
         line_items.order_id so embedded lookups use an index scan.

      Fail if the agent misidentifies the cause as application-level N+1
      (calls from client code), blames the orders table, recommends only
      pagination without addressing the index, or gives vague advice.
    `,
  });

  checks.push({
    name: 'correctly diagnosed embedding N+1 and proposed index fix',
    passed: verdict.passed,
    judgeNotes: verdict.notes,
  });

  return {
    passed: namedLineItems && inspectedStats && identifiedPattern && proposedFix && verdict.passed,
    checks,
  };
};

export default scorer;
