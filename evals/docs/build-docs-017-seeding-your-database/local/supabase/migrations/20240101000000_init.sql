-- Studio booking app. Studios employ instructors, instructors teach classes,
-- and guests book classes.

create table public.studios (
  id bigint generated by default as identity primary key,
  name text not null unique,
  city text not null
);

create table public.instructors (
  id bigint generated by default as identity primary key,
  studio_id bigint not null references public.studios (id),
  name text not null,
  unique (studio_id, name)
);

create table public.classes (
  id bigint generated by default as identity primary key,
  instructor_id bigint not null references public.instructors (id),
  title text not null,
  starts_at timestamptz not null
);

create table public.bookings (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes (id),
  guest_email text not null
);
